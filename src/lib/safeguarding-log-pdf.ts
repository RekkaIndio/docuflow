function renderLinkedCqcSection(builder: StandardPdfBuilder, details?: LinkedCqcRecordPdfData | null): void {
  builder.addSection('Linked CQC notification', { marginTop: 16 });
  if (!details) {
    builder.addParagraph('No CQC notification log is linked to this safeguarding entry.');
    return;
  }

  const info: StandardPdfMetaItem[] = [
    { label: 'CQC running log', value: details.runningLogNumber ? `#${details.runningLogNumber}` : undefined },
    { label: 'Unique reference', value: coerce(details.uniqueReferenceNumber) },
    { label: 'Incident date', value: formatDate(details.incidentDate) },
    { label: 'Notification date', value: formatDate(details.cqcNotificationDate) },
    { label: 'Date closed', value: formatDate(details.dateClosed) },
    { label: 'Recorded', value: formatDateTime(details.createdAt) },
  ].filter((item) => item.value) as StandardPdfMetaItem[];

  if (info.length) {
    builder.addInfoGrid(info, { columns: Math.min(info.length, 3) });
  }

  builder.addField('Duty of candour upheld', formatBoolean(details.dutyOfCandourUpheld), { chip: booleanChip(details.dutyOfCandourUpheld) });
  builder.addField('Investigation complete', formatBoolean(details.investigationComplete), { chip: booleanChip(details.investigationComplete) });
  builder.addField('Lessons learnt complete', formatBoolean(details.lessonsLearntComplete), { chip: booleanChip(details.lessonsLearntComplete) });
  builder.addField('Root cause analysis complete', formatBoolean(details.rootCauseAnalysisComplete), { chip: booleanChip(details.rootCauseAnalysisComplete) });
  builder.addField('Safeguarding workflow complete', formatBoolean(details.sovaCompleted), { chip: booleanChip(details.sovaCompleted) });
  builder.addField('Incident details', details.incidentDetails ?? 'Not recorded');
  builder.addField('Outcome', details.outcome ?? 'Not recorded');
}

function formatDate(value: Nullable<string>): string | undefined {
  if (!value) return undefined;
  try {
    return format(parseISO(value), 'dd MMM yyyy');
  } catch (error) {
    const date = new Date(value);
    if (!Number.isNaN(date.getTime())) {
      return format(date, 'dd MMM yyyy');
    }
    return value;
  }
}

function formatDateTime(value: Nullable<string>): string | undefined {
  if (!value) return undefined;
  try {
    return format(parseISO(value), 'dd MMM yyyy • HH:mm');
  } catch (error) {
    const date = new Date(value);
    if (!Number.isNaN(date.getTime())) {
      return format(date, 'dd MMM yyyy • HH:mm');
    }
    return value;
  }
}

function formatBoolean(value: TriState): string {
  if (value === true) return 'Yes';
  if (value === false) return 'No';
  return 'Not recorded';
}

function booleanChip(value: TriState): 'yes' | 'no' | 'info' {
  if (value === true) return 'yes';
  if (value === false) return 'no';
  return 'info';
}

function coerce(value: Nullable<string | number>): string | undefined {
  if (value === null || value === undefined) return undefined;
  const str = String(value).trim();
  return str.length > 0 ? str : undefined;
}
