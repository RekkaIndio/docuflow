import { format, parseISO } from 'date-fns';
import { StandardPdfBuilder, StandardPdfMetaItem } from '@/lib/pdf/standard-layout';

type Nullable<T> = T | null | undefined;

type TriState = boolean | null | undefined;

export interface LessonsRecordPdfData {
  form?: Record<string, any>;
  actions?: Array<{ action?: string; owner?: string; timescale?: string; status?: string }>;
  createdAt?: string | null;
  recordType?: string | null;
}

export interface RcaRecordPdfData {
  form?: Record<string, any>;
  actions?: Array<{ action?: string; owner?: string; timescale?: string; status?: string }>;
  createdAt?: string | null;
  recordType?: string | null;
}

export interface LinkedCqcRecordPdfData {
  runningLogNumber?: number | null;
  uniqueReferenceNumber?: string | null;
  incidentDate?: string | null;
  cqcNotificationDate?: string | null;
  dateClosed?: string | null;
  createdAt?: string | null;
  incidentDetails?: string | null;
  dutyOfCandourUpheld?: boolean | null;
  investigationComplete?: boolean | null;
  lessonsLearntComplete?: boolean | null;
  rootCauseAnalysisComplete?: boolean | null;
  sovaCompleted?: boolean | null;
  outcome?: string | null;
}

export interface SafeguardingLogPdfData {
  workspaceName: string;
  generatedBy?: string | null;
  entry: {
    runningLogNumber: number;
    residentName: string;
    incidentDate?: string | null;
    dateSovaRaised?: string | null;
    dateClosed?: string | null;
    createdAt?: string | null;
    dutyOfCandourUpheld: TriState;
    investigationComplete: TriState;
    cqcNotificationSubmitted: TriState;
    lessonsLearntComplete: TriState;
    rootCauseAnalysisComplete: TriState;
    incidentDetails?: string | null;
    outcome?: string | null;
    lessonsLearntRecordLabel?: string | null;
    rootCauseAnalysisRecordLabel?: string | null;
    cqcLogLabel?: string | null;
  };
  lessonsRecord?: LessonsRecordPdfData;
  rcaRecord?: RcaRecordPdfData;
  linkedCqcRecord?: LinkedCqcRecordPdfData;
}

export function generateSafeguardingLogPdf(data: SafeguardingLogPdfData): ArrayBuffer {
  const generatedAt = new Date().toISOString();
  const meta: StandardPdfMetaItem[] = [
    { label: 'Workspace', value: data.workspaceName },
    { label: 'Resident', value: data.entry.residentName },
    { label: 'Running Log', value: `#${data.entry.runningLogNumber}` },
    { label: 'Incident Date', value: formatDate(data.entry.incidentDate) },
    { label: 'Date SOVA Raised', value: formatDate(data.entry.dateSovaRaised) },
    { label: 'Date Closed', value: formatDate(data.entry.dateClosed) },
    { label: 'Recorded', value: formatDateTime(data.entry.createdAt) },
    { label: 'Generated By', value: data.generatedBy },
  ].filter((item) => item.value) as StandardPdfMetaItem[];

  const builder = new StandardPdfBuilder({
    title: 'Safeguarding (SOVA) Report',
    subtitle: `Log #${data.entry.runningLogNumber} — ${data.entry.residentName}`,
    meta,
    generatedAt: formatDateTime(generatedAt),
  });

  builder.doc.setProperties({
    title: `SOVA Log #${data.entry.runningLogNumber} — ${data.entry.residentName}`,
    subject: 'Safeguarding (SOVA) log export',
    author: data.generatedBy ?? 'Docuflow',
  });

  const linkedRecords: StandardPdfMetaItem[] = [
    { label: 'Lessons learned record', value: data.entry.lessonsLearntRecordLabel },
    { label: 'RCA record', value: data.entry.rootCauseAnalysisRecordLabel },
    { label: 'CQC log', value: data.entry.cqcLogLabel },
  ].filter((item) => item.value) as StandardPdfMetaItem[];

  if (linkedRecords.length) {
    builder.addSection('Linked records');
    builder.addInfoGrid(linkedRecords, { columns: Math.min(linkedRecords.length, 3) });
  }

  builder.addSection('Status Overview', { marginTop: 12 });
  builder.addField('Duty of candour upheld', formatBoolean(data.entry.dutyOfCandourUpheld), { chip: booleanChip(data.entry.dutyOfCandourUpheld) });
  builder.addField('Investigation complete', formatBoolean(data.entry.investigationComplete), { chip: booleanChip(data.entry.investigationComplete) });
  builder.addField('CQC notification submitted', formatBoolean(data.entry.cqcNotificationSubmitted), { chip: booleanChip(data.entry.cqcNotificationSubmitted) });
  builder.addField('Lessons learnt complete', formatBoolean(data.entry.lessonsLearntComplete), { chip: booleanChip(data.entry.lessonsLearntComplete) });
  builder.addField('Root cause analysis complete', formatBoolean(data.entry.rootCauseAnalysisComplete), { chip: booleanChip(data.entry.rootCauseAnalysisComplete) });

  builder.addSection('Narrative', { marginTop: 16 });
  builder.addField('Incident details', data.entry.incidentDetails ?? 'Not recorded', { emphasis: true });
  builder.addField('Outcome', data.entry.outcome ?? 'Not recorded');

  renderLessonsSection(builder, data.lessonsRecord);
  renderRcaSection(builder, data.rcaRecord);
  renderLinkedCqcSection(builder, data.linkedCqcRecord);

  builder.addFooter();
  return builder.doc.output('arraybuffer') as ArrayBuffer;
}

export function getSafeguardingLogPdfFilename(workspaceName: string, runningNumber: number, residentName?: string | null): string {
  const slug = [workspaceName, `sova-${runningNumber}`, residentName ?? 'log']
    .map((part) => (part ?? '').trim().replace(/[^a-zA-Z0-9]+/g, '_').replace(/_{2,}/g, '_').replace(/^_|_$/g, '').toLowerCase())
    .filter(Boolean)
    .join('__');
  return `${slug || 'sova-log'}.pdf`;
}

function renderLessonsSection(builder: StandardPdfBuilder, details?: LessonsRecordPdfData): void {
  builder.addSection('Lessons learned', { marginTop: 16 });
  if (!details) {
    builder.addParagraph('No lessons learned record is linked or the record could not be retrieved.');
    return;
  }

  const info: StandardPdfMetaItem[] = [
    { label: 'Record type', value: coerce(details.recordType) },
    { label: 'Event type', value: coerce(details.form?.eventType) },
    { label: 'Event date', value: formatDate(details.form?.date) },
    { label: 'Location', value: coerce(details.form?.location) },
    { label: 'People involved', value: coerce(details.form?.peopleInvolved) },
    { label: 'Created', value: formatDateTime(details.createdAt) },
  ].filter((item) => item.value) as StandardPdfMetaItem[];

  if (info.length) {
    builder.addInfoGrid(info, { columns: Math.min(info.length, 3) });
  }

  builder.addField('Summary of events', details.form?.summaryOfEvents ?? details.form?.description ?? 'Not recorded');
  builder.addField('Lessons learned', details.form?.lessonsLearned ?? 'Not recorded');
  const monitoring = [details.form?.monitoring, details.form?.oversight].filter(Boolean).join('\n\n');
  if (monitoring) {
    builder.addField('Monitoring & oversight', monitoring);
  }

  if (details.actions && details.actions.length > 0) {
    builder.addSubheading('Actions', { marginTop: 12, accent: true });
    builder.addTable({
      columns: [
        { key: 'action', header: 'Action', width: 100 },
        { key: 'owner', header: 'Owner', width: 60 },
        { key: 'timescale', header: 'Timescale', width: 50 },
        { key: 'status', header: 'Status', width: 45 },
      ],
      rows: details.actions.map((item, index) => ({
        action: item.action || `Action ${index + 1}`,
        owner: item.owner || 'Not assigned',
        timescale: item.timescale || 'Not set',
        status: item.status || 'Open',
      })),
      stripe: true,
    });
  }
}

