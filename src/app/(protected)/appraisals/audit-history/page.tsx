"use client";

import React, { useState, useEffect } from "react";
import { db } from "@/lib/firebase";
import { doc, getDoc } from "firebase/firestore";
import { workspaceDocPath } from "@/lib/paths";
import { useAuth } from "@/hooks/use-auth";
import Link from "next/link";

// PDF Generation utility
const generateAppraisalPDF = async (appraisalData: any, appraisalTitle: string, month: number) => {
  const htmlContent = `
    <!DOCTYPE html>
    <html>
    <head>
      <meta charset="utf-8">
      <title>${appraisalTitle} - ${new Date(2025, month).toLocaleString('default', { month: 'long' })} 2025</title>
      <style>
        body { font-family: Arial, sans-serif; margin: 40px; color: #333; }
        .header { text-align: center; border-bottom: 2px solid #2563eb; padding-bottom: 20px; margin-bottom: 30px; }
        .title { font-size: 24px; font-weight: bold; color: #2563eb; margin-bottom: 10px; }
        .subtitle { font-size: 16px; color: #666; }
        .section { margin-bottom: 25px; }
        .section-title { font-size: 18px; font-weight: bold; color: #2563eb; margin-bottom: 10px; border-bottom: 1px solid #e5e7eb; padding-bottom: 5px; }
        .field { margin-bottom: 15px; }
        .field-label { font-weight: bold; color: #374151; }
        .field-value { margin-top: 5px; line-height: 1.5; }
        .signature { margin-top: 40px; border-top: 1px solid #e5e7eb; padding-top: 20px; }
        .signature-title { font-weight: bold; margin-bottom: 10px; }
        .footer { margin-top: 50px; text-align: center; font-size: 12px; color: #666; border-top: 1px solid #e5e7eb; padding-top: 20px; }
      </style>
    </head>
    <body>
      <div class="header">
        <div class="title">${appraisalTitle}</div>
        <div class="subtitle">${new Date(2025, month).toLocaleString('default', { month: 'long' })} 2025</div>
      </div>

      <div class="content">
        ${Object.entries(appraisalData).map(([key, value]: [string, any]) => {
          if (key === 'signature' || key === 'date') return '';
          return `
            <div class="section">
              <div class="section-title">${key.replace(/([A-Z])/g, ' $1').replace(/^./, str => str.toUpperCase())}</div>
              <div class="field-value">${value || 'Not provided'}</div>
            </div>
          `;
        }).join('')}

        ${appraisalData.signature ? `
          <div class="signature">
            <div class="signature-title">Signature</div>
            <div class="field-value">${appraisalData.signature}</div>
            ${appraisalData.date ? `<div class="field-value">Date: ${appraisalData.date}</div>` : ''}
          </div>
        ` : ''}
      </div>

      <div class="footer">
        Generated by Docuflow on ${new Date().toLocaleDateString()}
      </div>
    </body>
    </html>
  `;

  // For now, return the HTML content - in a real implementation, you'd use Puppeteer or similar
  return htmlContent;
};

const appraisalCards = [
  { title: 'Activities supervision', slug: 'activities-supervision' },
  { title: 'Admin supervision', slug: 'admin-supervision' },
  { title: 'Appraisal form', slug: 'staff-appraisal' },
  { title: 'Carers supervision', slug: 'carers-supervision' },
  { title: 'Chef supervision', slug: 'chef-supervision' },
  { title: 'Clinical lead supervision', slug: 'clinical-lead-supervision' },
  { title: 'Deputy supervision', slug: 'deputy-supervision' },
  { title: 'Domestic staff supervision', slug: 'domestic-staff-supervision' },
  { title: 'Housekeeping supervision', slug: 'housekeeping-supervision' },
  { title: 'Kitchen assistant supervision', slug: 'kitchen-assistant-supervision' },
  { title: 'Maintenence person supervision', slug: 'maintenence-person-supervision' },
  { title: 'Nurses supervision', slug: 'nurses-supervision' },
  { title: 'Reception supervision', slug: 'reception-supervision' },
  { title: 'Senior Carer / Care Team Manager supervision', slug: 'senior-carer-supervision' },
];

export default function AuditHistoryPage() {
  const { user } = useAuth();
  const [completionStatus, setCompletionStatus] = useState<Record<string, Record<string, boolean>>>({});
  const [appraisalData, setAppraisalData] = useState<Record<string, any>>({});
  const [loading, setLoading] = useState(true);
  const [selectedAppraisal, setSelectedAppraisal] = useState<string | null>(null);
  const [pdfViewer, setPdfViewer] = useState<{ appraisal: string; month: number; content?: string | null } | null>(null);

  // Load completion status and appraisal data from Firebase
  useEffect(() => {
    const loadData = async () => {
      if (!user?.id) return;

      try {
        const docRef = (user as any)?.workspaceId
          ? doc(db, workspaceDocPath((user as any).workspaceId, `appraisal-tracker/${user.id}`, (user as any).organisationId))
          : doc(db, "appraisal-tracker", user.id);

        const docSnap = await getDoc(docRef);

        if (docSnap.exists()) {
          const data = docSnap.data();
          setCompletionStatus(data.completionStatus || {});
          setAppraisalData(data.appraisalData || {});
        }
      } catch (error) {
        console.error("Error loading data:", error);
      } finally {
        setLoading(false);
      }
    };

    loadData();
  }, [user?.id]);

  // Get all completed appraisals organized by appraisal type
  const getCompletedAppraisalsByType = () => {
    const result: Record<string, { month: number; role: string }[]> = {};

    Object.keys(completionStatus).forEach(role => {
      const roleEntries = completionStatus[role];
      Object.keys(roleEntries).forEach(key => {
        if (roleEntries[key]) {
          const [appraisalSlug, monthStr] = key.split('-');
          const month = parseInt(monthStr);

          if (!result[appraisalSlug]) {
            result[appraisalSlug] = [];
          }
          result[appraisalSlug].push({ month, role });
        }
      });
    });

    return result;
  };

  const completedByType = getCompletedAppraisalsByType();

  const handleViewPDF = async (appraisal: string, month: number) => {
    try {
      // Try to get appraisal data from Firebase first, then localStorage as fallback
      const firebaseKey = `${appraisal}-${month}`;
      let formData = appraisalData[firebaseKey]?.data;

      if (!formData) {
        // Fallback to localStorage
        const formKey = `${appraisal}-form`;
        const storedData = localStorage.getItem(formKey);
        if (storedData) {
          formData = JSON.parse(storedData);
        }
      }

      if (formData) {
        const appraisalTitle = appraisalCards.find(card => card.slug === appraisal)?.title || appraisal;
        const pdfContent = await generateAppraisalPDF(formData, appraisalTitle, month);
        setPdfViewer({ appraisal, month, content: pdfContent });
      } else {
        // If no data found, show placeholder
        setPdfViewer({ appraisal, month, content: null });
      }
    } catch (error) {
      console.error('Error generating PDF:', error);
      setPdfViewer({ appraisal, month, content: null });
    }
  };

  const handleDownloadPDF = async (appraisal: string, month: number) => {
    try {
      // Try to get appraisal data from Firebase first, then localStorage as fallback
      const firebaseKey = `${appraisal}-${month}`;
      let formData = appraisalData[firebaseKey]?.data;

      if (!formData) {
        // Fallback to localStorage
        const formKey = `${appraisal}-form`;
        const storedData = localStorage.getItem(formKey);
        if (storedData) {
          formData = JSON.parse(storedData);
        }
      }

      if (formData) {
        const appraisalTitle = appraisalCards.find(card => card.slug === appraisal)?.title || appraisal;
        const pdfContent = await generateAppraisalPDF(formData, appraisalTitle, month);

        // Create a blob and download
        const blob = new Blob([pdfContent], { type: 'text/html' });
        const url = URL.createObjectURL(blob);
        const a = document.createElement('a');
        a.href = url;
        a.download = `${appraisal}-${month}.html`;
        document.body.appendChild(a);
        a.click();
        document.body.removeChild(a);
        URL.revokeObjectURL(url);
      } else {
        alert('No appraisal data found for download');
      }
    } catch (error) {
      console.error('Error downloading PDF:', error);
      alert('Error downloading PDF. Please try again.');
    }
  };

  const getMonthName = (monthIndex: number) => {
    return ['January', 'February', 'March', 'April', 'May', 'June',
            'July', 'August', 'September', 'October', 'November', 'December'][monthIndex];
  };

  if (loading) {
    return (
      <div className="min-h-screen bg-gray-50 flex items-center justify-center">
        <div className="flex items-center space-x-2">
          <div className="w-6 h-6 border-2 border-blue-500 border-t-transparent rounded-full animate-spin"></div>
          <span className="text-gray-600">Loading audit history...</span>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen bg-gray-50">
      {/* Header */}
      <div className="bg-gradient-to-r from-blue-600 to-indigo-600 text-white p-8 rounded-b-2xl shadow-lg relative overflow-hidden">
        <div className="absolute inset-0 opacity-5 pointer-events-none select-none">
          <div className="absolute top-0 right-0 w-96 h-96 bg-white rounded-full -translate-y-48 translate-x-48"></div>
          <div className="absolute bottom-0 left-0 w-64 h-64 bg-blue-400 rounded-full translate-y-32 -translate-x-32"></div>
        </div>
        <div className="relative z-10">
          <div className="flex items-center gap-4 mb-2">
            <Link href="/appraisals" className="text-white/80 hover:text-white transition-colors">
              <svg width="24" height="24" viewBox="0 0 24 24" fill="none" className="text-current">
                <path d="M15 18l-6-6 6-6" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
              </svg>
            </Link>
            <h1 className="text-3xl font-bold leading-tight tracking-tight">Audit History</h1>
          </div>
          <div className="mt-1 text-slate-200 text-base leading-relaxed">View all completed appraisals and reports organized by type</div>
        </div>
      </div>

      {/* Main Content */}
      <div className="max-w-7xl mx-auto px-4 sm:px-8 lg:px-16 py-8">
        {Object.keys(completedByType).length === 0 ? (
          <div className="text-center py-16">
            <div className="w-20 h-20 rounded-full bg-gray-100 text-gray-400 flex items-center justify-center mx-auto mb-6">
              <svg width="32" height="32" viewBox="0 0 24 24" fill="none" className="text-current">
                <path d="M9 5H7a2 2 0 00-2 2v10a2 2 0 002 2h8a2 2 0 002-2V7a2 2 0 00-2-2h-2M9 5a2 2 0 002 2h2a2 2 0 002-2M9 5a2 2 0 012-2h2a2 2 0 012 2" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
              </svg>
            </div>
            <h3 className="text-xl font-semibold text-gray-900 mb-2">No Completed Appraisals</h3>
            <p className="text-gray-600 mb-6">Complete some appraisals to see them in your audit history</p>
            <Link
              href="/appraisals"
              className="inline-flex items-center gap-2 px-6 py-3 bg-gradient-to-r from-blue-600 to-indigo-600 text-white rounded-lg font-medium hover:shadow-lg transition-shadow"
            >
              <svg width="20" height="20" viewBox="0 0 24 24" fill="none" className="text-current">
                <path d="M12 4v16m8-8H4" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
              </svg>
              Start an Appraisal
            </Link>
          </div>
        ) : (
          <div className="space-y-8">
            {Object.keys(completedByType).map(appraisalSlug => {
              const appraisalTitle = appraisalCards.find(card => card.slug === appraisalSlug)?.title || appraisalSlug;
              const reports = completedByType[appraisalSlug];

              return (
                <div key={appraisalSlug} className="bg-white rounded-2xl shadow-lg border border-gray-200 overflow-hidden">
                  <div className="bg-gradient-to-r from-blue-600 to-indigo-600 p-6">
                    <div className="flex items-center gap-3">
                      <div className="w-12 h-12 rounded-xl bg-white/20 text-white flex items-center justify-center">
                        <svg width="24" height="24" viewBox="0 0 24 24" fill="none" className="text-current">
                          <path d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                        </svg>
                      </div>
                      <div>
                        <h2 className="text-xl font-bold text-white">{appraisalTitle}</h2>
                        <p className="text-blue-100 text-sm">{reports.length} completed report{reports.length !== 1 ? 's' : ''}</p>
                      </div>
                    </div>
                  </div>

                  <div className="p-6">
                    <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
                      {reports.map(({ month, role }, index) => (
                        <div key={`${appraisalSlug}-${month}-${index}`} className="border border-gray-200 rounded-xl p-4 hover:shadow-md transition-shadow">
                          <div className="flex items-start justify-between mb-3">
                            <div className="flex items-center gap-2">
                              <div className="w-8 h-8 rounded-lg bg-green-100 text-green-600 flex items-center justify-center">
                                <svg width="16" height="16" viewBox="0 0 24 24" fill="none" className="text-current">
                                  <path d="M9 12l2 2 4-4m6 2a9 9 0 11-18 0 9 9 0 0118 0z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                                </svg>
                              </div>
                              <div>
                                <div className="font-medium text-gray-900 text-sm">{getMonthName(month)} 2025</div>
                                <div className="text-xs text-gray-600">{role}</div>
                              </div>
                            </div>
                          </div>

                          <div className="flex gap-2">
                            <button
                              onClick={() => handleViewPDF(appraisalSlug, month)}
                              className="flex-1 flex items-center justify-center gap-2 px-3 py-2 bg-blue-600 text-white text-xs rounded-lg hover:bg-blue-700 transition-colors"
                            >
                              <svg width="12" height="12" viewBox="0 0 24 24" fill="none" className="text-current">
                                <path d="M15 12a3 3 0 11-6 0 3 3 0 016 0z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                                <path d="M2.458 12C3.732 7.943 7.523 5 12 5c4.478 0 8.268 2.943 9.542 7-1.274 4.057-5.064 7-9.542 7-4.477 0-8.268-2.943-9.542-7z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                              </svg>
                              View PDF
                            </button>
                            <button
                              onClick={() => handleDownloadPDF(appraisalSlug, month)}
                              className="flex items-center justify-center gap-2 px-3 py-2 bg-gray-600 text-white text-xs rounded-lg hover:bg-gray-700 transition-colors"
                            >
                              <svg width="12" height="12" viewBox="0 0 24 24" fill="none" className="text-current">
                                <path d="M12 10v6m0 0l-3-3m3 3l3-3m2 8H7a2 2 0 01-2-2V5a2 2 0 012-2h5.586a1 1 0 01.707.293l5.414 5.414a1 1 0 01.293.707V19a2 2 0 01-2 2z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                              </svg>
                              Download
                            </button>
                          </div>
                        </div>
                      ))}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        )}
      </div>

      {/* PDF Viewer Modal */}
      {pdfViewer && (
        <div className="fixed inset-0 bg-black/75 flex items-center justify-center z-50 p-4">
          <div className="bg-white rounded-2xl shadow-xl max-w-5xl w-full max-h-[90vh] overflow-hidden">
            <div className="p-4 border-b border-gray-200 flex items-center justify-between">
              <div className="flex items-center gap-3">
                <div className="w-8 h-8 rounded-lg bg-blue-100 text-blue-600 flex items-center justify-center">
                  <svg width="16" height="16" viewBox="0 0 24 24" fill="none" className="text-current">
                    <path d="M9 5H7a2 2 0 00-2 2v10a2 2 0 002 2h8a2 2 0 002-2V7a2 2 0 00-2-2h-2M9 5a2 2 0 002 2h2a2 2 0 002-2M9 5a2 2 0 012-2h2a2 2 0 012 2" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                  </svg>
                </div>
                <div>
                  <h3 className="font-semibold text-gray-900">
                    {appraisalCards.find(card => card.slug === pdfViewer.appraisal)?.title || pdfViewer.appraisal}
                  </h3>
                  <p className="text-sm text-gray-600">{getMonthName(pdfViewer.month)} 2025</p>
                </div>
              </div>
              <div className="flex items-center gap-2">
                <button
                  onClick={() => handleDownloadPDF(pdfViewer.appraisal, pdfViewer.month)}
                  className="px-3 py-1 bg-gray-600 text-white text-sm rounded-lg hover:bg-gray-700 transition-colors flex items-center gap-2"
                >
                  <svg width="14" height="14" viewBox="0 0 24 24" fill="none" className="text-current">
                    <path d="M12 10v6m0 0l-3-3m3 3l3-3m2 8H7a2 2 0 01-2-2V5a2 2 0 012-2h5.586a1 1 0 01.707.293l5.414 5.414a1 1 0 01.293.707V19a2 2 0 01-2 2z" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                  </svg>
                  Download
                </button>
                <button
                  onClick={() => setPdfViewer(null)}
                  className="w-8 h-8 rounded-lg bg-gray-100 hover:bg-gray-200 text-gray-600 hover:text-gray-800 flex items-center justify-center transition-colors"
                >
                  <svg width="16" height="16" viewBox="0 0 24 24" fill="none" className="text-current">
                    <path d="M6 18L18 6M6 6l12 12" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                  </svg>
                </button>
              </div>
            </div>
            <div className="p-4 bg-gray-50">
              {pdfViewer.content ? (
                <div className="bg-white rounded-lg border-2 border-gray-300 max-h-96 overflow-y-auto">
                  <iframe
                    srcDoc={pdfViewer.content}
                    className="w-full h-96 border-0"
                    title={`${pdfViewer.appraisal} PDF`}
                  />
                </div>
              ) : (
                <div className="bg-white rounded-lg border-2 border-dashed border-gray-300 p-12 text-center">
                  <div className="w-16 h-16 rounded-full bg-gray-100 text-gray-400 flex items-center justify-center mx-auto mb-4">
                    <svg width="24" height="24" viewBox="0 0 24 24" fill="none" className="text-current">
                      <path d="M9 5H7a2 2 0 00-2 2v10a2 2 0 002 2h8a2 2 0 002-2V7a2 2 0 00-2-2h-2M9 5a2 2 0 002 2h2a2 2 0 002-2M9 5a2 2 0 012-2h2a2 2 0 012 2" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round"/>
                    </svg>
                  </div>
                  <h4 className="text-lg font-medium text-gray-900 mb-2">PDF Preview</h4>
                  <p className="text-gray-600 mb-4">No appraisal data found for this report</p>
                  <p className="text-sm text-gray-500">File: {pdfViewer.appraisal}-{pdfViewer.month}.pdf</p>
                </div>
              )}
            </div>
          </div>
        </div>
      )}
    </div>
  );
}